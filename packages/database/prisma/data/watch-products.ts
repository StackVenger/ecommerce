export type WatchAttributeType = 'COLOR' | 'SIZE' | 'MATERIAL' | 'STYLE' | 'CUSTOM';

export interface WatchVariantSeed {
  name: string;
  sku: string;
  /** attribute name -> value */
  values: Record<string, string>;
  price: number;
  compareAtPrice: number | null;
  quantity: number;
  /** Index into the product's `images` used as this variant's photo / swatch. */
  image: number | null;
}

export interface WatchProductSeed {
  name: string;
  slug: string;
  sku: string;
  brandSlug: string | null;
  categorySlug: string;
  price: number;
  compareAtPrice: number | null;
  costPrice: number;
  /** Stock for products without variants (variant products sum their variants). */
  quantity: number | null;
  shortDescription: string;
  description: string;
  tags: string[];
  isFeatured: boolean;
  images: string[];
  variants?: {
    attributes: { name: string; type: WatchAttributeType; values: string[] }[];
    items: WatchVariantSeed[];
  };
  /** How many days ago the product was listed (drives "New Arrivals" ordering). */
  ageDays: number;
}

